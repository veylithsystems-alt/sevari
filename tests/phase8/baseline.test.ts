/**
 * Baseline report v1 (Phase 8 exit, §11). A simulated week: all 100 corpus enquiries, five trades, through
 * the whole pipeline (intake → acknowledgement → analysis → draft → owner decision → send), with a scripted
 * owner (approves most after a couple of minutes, edits some, rejects a few, never answers some). Writes
 * docs/reports/baseline-v1.md when SEVARI_BASELINE=1; otherwise it just checks the floors hold.
 * Environment: build machine, fake provider, no model. Not a performance figure for the target box.
 */
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';
import { expect, it } from 'vitest';
import { withTenant } from '@sevari/db';
import { weeklyMetrics, type WeeklyMetrics } from '@sevari/metrics';
import { draftFor, harness } from '../support/hitl-harness.ts';

const ROOT = resolve(import.meta.dirname, '..', '..');
interface Case { id: string; trade: string; text: string; from_name?: string }
const corpus = (): Case[] => readdirSync(join(ROOT, 'eval', 'corpus')).filter((f) => f.endsWith('.jsonl')).sort()
  .flatMap((f) => readFileSync(join(ROOT, 'eval', 'corpus', f), 'utf8').split('\n').filter(Boolean).map((l) => JSON.parse(l) as Case));

it('baseline: a simulated week across five trades holds every floor', async () => {
  const cases = corpus();
  const trades = [...new Set(cases.map((c) => c.trade))];
  const perTrade: Record<string, WeeklyMetrics> = {};
  let i = 0;
  for (const [n, trade] of trades.entries()) {
    const x = await harness(`base${n}`, 90 + n, undefined, trade);
    try {
      const start = new Date(x.clock.nowMs() - 1);
      for (const c of cases.filter((k) => k.trade === trade)) {
        i++;
        const m = await x.send(c.text, `c${i}@example.com`);
        const r = await x.process(m.messageId);
        const d = await draftFor(x, r.enquiryId);
        const q = d ? await x.question(`draft:${d.id}`) : undefined;
        if (q) {
          // Scripted owner: ~5% never answer, ~5% reject, ~10% edit (wording only), the rest approve after 2-8 minutes.
          const roll = i % 20;
          if (roll !== 0) {
            x.clock.advance((2 + (i % 7)) * 60_000);
            const response = roll === 1 ? 'reject' : roll === 2 || roll === 3 ? 'edit' : 'approve';
            await x.answer({ questionId: q.id, responderId: x.owner, response, digestSeen: q.digest, ...(response === 'edit' ? { detail: `Hello, thanks for getting in touch. The team will confirm the details shortly.` } : {}) });
          }
        }
        x.clock.advance(30 * 60_000);
      }
      await x.drain();
      perTrade[trade] = await withTenant(x.h.db, x.t, (tx) => weeklyMetrics(tx, start, new Date(x.clock.nowMs() + 1), x.clock.nowMs()));
    } finally {
      await x.close();
    }
  }
  const all = Object.values(perTrade);
  for (const m of all) expect(m.floors).toEqual({ unauthorisedSends: 0, suppressedSends: 0 });
  // Everyone except those who asked to stop was acknowledged.
  for (const m of all) expect(m.acknowledged).toBe(m.enquiries - m.optOuts);
  expect(all.reduce((a, m) => a + m.enquiries, 0)).toBe(cases.length);
  if (process.env['SEVARI_BASELINE'] !== '1') return;

  const sum = (f: (m: WeeklyMetrics) => number) => all.reduce((a, m) => a + f(m), 0);
  const evalBase = JSON.parse(readFileSync(join(ROOT, 'eval', 'baseline.json'), 'utf8')) as Record<string, number>;
  const row = (trade: string, m: WeeklyMetrics) => `| ${trade} | ${m.enquiries} | ${m.acknowledged} | ${m.optOuts} | ${m.replied} | ${(m.routes['human_only'] ?? 0) + (m.routes['unknown'] ?? 0)} | ${m.drafts.edited} | ${m.drafts.rejected} | ${m.ownerEditRate ?? '—'} | ${m.ownerMinutesPerEnquiry ?? '—'} | ${m.floors.unauthorisedSends + m.floors.suppressedSends} |`;
  const unknowns = new Map<string, number>();
  for (const m of all) for (const u of m.unknownTop) unknowns.set(u.topic, (unknowns.get(u.topic) ?? 0) + u.count);
  const report = [
    '# Baseline report v1', '',
    '**Generated by** `SEVARI_BASELINE=1 pnpm vitest run tests/phase8/baseline.test.ts`. **Environment:** build machine, fake email/SMS provider, no AI model (templates only), scripted owner. Speed figures here are **not** target-box measurements (see `docs/ops/model-benchmark.md` and F7).', '',
    '## What was simulated',
    `All ${cases.length} corpus enquiries (five trades, 20 each) arrived 30 minutes apart, one business per trade, each seeded with that trade's confirmed records. The scripted owner approved most drafts after 2 to 8 minutes, changed the wording of about 10%, turned down about 5%, and never answered about 5%.`, '',
    '## Floors (must be zero)',
    `- Messages sent without a human approval or an earned grant: **${sum((m) => m.floors.unauthorisedSends)}**`,
    `- Messages sent to someone who had opted out: **${sum((m) => m.floors.suppressedSends)}**`, '',
    '## The week, by trade', '',
    '| Trade | Enquiries | Acknowledged | Asked to stop (not messaged) | Replies sent | Needed the owner | Edited | Turned down | Edit rate | Owner minutes / enquiry | Floor breaches |',
    '|---|---|---|---|---|---|---|---|---|---|---|',
    ...Object.entries(perTrade).map(([t, m]) => row(t, m)),
    `| **All** | ${sum((m) => m.enquiries)} | ${sum((m) => m.acknowledged)} | ${sum((m) => m.optOuts)} | ${sum((m) => m.replied)} | ${sum((m) => (m.routes['human_only'] ?? 0) + (m.routes['unknown'] ?? 0))} | ${sum((m) => m.drafts.edited)} | ${sum((m) => m.drafts.rejected)} | | | ${sum((m) => m.floors.unauthorisedSends + m.floors.suppressedSends)} |`, '',
    '## What happens to enquiries (routes)', '',
    '| Route | Count | Meaning |', '|---|---|---|',
    ...([['answer', 'a reply drafted from confirmed records, sent after approval'], ['clarify', 'one specific question back to the customer'], ['unknown', 'the records don\'t cover it: the owner is asked'], ['human_only', 'complaints, legal, data rights and similar: the owner handles it'], ['safety_first', 'danger described: the safety message went out at once'], ['opt_out', 'STOP: suppressed, nothing more sent']] as const)
      .map(([r, what]) => `| ${r} | ${sum((m) => m.routes[r] ?? 0)} | ${what} |`), '',
    '## Most common gaps in the records', '',
    ...[...unknowns].sort((a, b) => b[1] - a[1]).slice(0, 8).map(([t, n]) => `- ${t.replace(/^knowledge:/, '').replace(/[:_]/g, ' ')}: ${n}`), '',
    '## Rules engine accuracy on the same corpus (accepted baseline, `eval/baseline.json`)', '',
    `Route ${evalBase['route']}% · intent ${evalBase['intent']}% · service ${evalBase['service']}% · postcode ${evalBase['outward']}% · urgency ${evalBase['urgency']}% · risk-to-life recall ${evalBase['safety_recall']}% · always-human recall ${evalBase['human_recall']}%.`, '',
    '## What this baseline does not yet show',
    '- Real owner behaviour and time saved (Value Gate, pilots).',
    '- Target-box speed with a real model (MB-1, MB-2).',
    '- Booking completion and resolution (Phase 9 lifecycle).',
    '- Cost per resolved enquiry (needs provider prices in use; texts are paying-customers-only, §87).', '',
  ].join('\n');
  writeFileSync(join(ROOT, 'docs', 'reports', 'baseline-v1.md'), report);
}, 300_000);
