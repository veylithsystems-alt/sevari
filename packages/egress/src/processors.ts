/**
 * Structured processor registry (contract §69). An allowed hostname is not a processor record:
 * this holds purpose, data categories, locations, sub-processors, terms, retention, transfers,
 * review status and the human approval. The egress allowlist references it by id.
 */
import { readFile } from 'node:fs/promises';
import { parse } from 'yaml';
import { z } from 'zod';
import type { EgressPolicy } from './allowlist.ts';

const Source = z.object({ url: z.string().url(), checked_on: z.string().date() });

export const ProcessorSchema = z.object({
  id: z.string().regex(/^[a-z0-9][a-z0-9-]{1,62}$/),
  name: z.string().min(1),
  role: z.enum(['processor', 'sub_processor', 'controller_to_controller', 'self']),
  purpose: z.string().min(1),
  data_categories: z.array(z.string().min(1)).min(1),
  data_locations: z.array(z.object({ data: z.string().min(1), location: z.string().min(1), source: Source.optional() })).min(1),
  sub_processors: z.object({ list_url: z.string().url().nullable(), notice_days: z.number().int().nonnegative().nullable(), source: Source.optional() }),
  terms: z.object({ dpa: z.string().min(1), terms_url: z.string().url().nullable() }),
  retention: z.string().min(1),
  transfer_mechanism: z.string().min(1),
  adr: z.string().regex(/^docs\/adr\//),
  /** Measured data destination where the provider allows it (§69 "test the actual destination"). */
  destination_test: z.string().nullable(),
  review: z.object({ status: z.enum(['draft', 'approved', 'suspended', 'retired']), reviewed_on: z.string().date().nullable(), next_review: z.string().date().nullable() }),
  /** §71: the auditable human approval. Required when status is approved. */
  approval: z.object({ approved_by: z.string().min(1), approved_on: z.string().date(), human_input_id: z.string().uuid().nullable() }).nullable(),
  unknowns: z.array(z.string()).default([]),
}).superRefine((p, ctx) => {
  if (p.review.status === 'approved' && !p.approval) ctx.addIssue({ code: 'custom', message: `${p.id}: approved without a recorded human approval (§71)` });
  if (p.review.status === 'approved' && !p.review.next_review) ctx.addIssue({ code: 'custom', message: `${p.id}: approved without a next review date` });
});
export type Processor = z.infer<typeof ProcessorSchema>;

export const ProcessorRegistrySchema = z.object({ version: z.literal(1), processors: z.array(ProcessorSchema) }).superRefine((r, ctx) => {
  const ids = new Set<string>();
  for (const p of r.processors) {
    if (ids.has(p.id)) ctx.addIssue({ code: 'custom', message: `duplicate processor id ${p.id}` });
    ids.add(p.id);
  }
});
export type ProcessorRegistry = z.infer<typeof ProcessorRegistrySchema>;

export async function loadProcessorRegistry(path: string): Promise<ProcessorRegistry> {
  return ProcessorRegistrySchema.parse(parse(await readFile(path, 'utf8')));
}

/**
 * T-PROC cross-check. Every allowlisted host must name an approved, in-date processor, and a private
 * network host must belong to a 'self' processor. Returns problems (empty = consistent).
 */
export function crossCheck(policy: EgressPolicy, registry: ProcessorRegistry, today: string): string[] {
  const problems: string[] = [];
  const byId = new Map(registry.processors.map((p) => [p.id, p]));
  for (const [cell, { hosts }] of Object.entries(policy.cells)) {
    for (const h of hosts) {
      const p = byId.get(h.processor);
      const where = `cell ${cell}: ${h.host}:${h.port}`;
      if (!p) { problems.push(`${where} references unknown processor '${h.processor}'`); continue; }
      if (p.review.status !== 'approved') problems.push(`${where}: processor ${p.id} is ${p.review.status}, not approved`);
      if (p.review.next_review && p.review.next_review < today) problems.push(`${where}: processor ${p.id} review overdue since ${p.review.next_review}`);
      if (h.private_network && p.role !== 'self') problems.push(`${where}: private_network is only allowed for 'self' infrastructure`);
    }
  }
  return problems;
}

/** Markdown processor register (§69), generated, never hand-edited. */
export function renderRegister(policy: EgressPolicy, registry: ProcessorRegistry): string {
  const lines = [
    '# Processor register',
    '',
    '> Generated by `pnpm register:generate` from `config/processors.yaml` and `config/egress.allowlist.yaml`. Do not edit by hand.',
    '',
  ];
  const approved = registry.processors.filter((p) => p.review.status === 'approved');
  if (approved.length === 0) {
    lines.push('**No processors are approved.** Sevari makes no outbound connections to third parties. Candidates awaiting an ADR and Dan\'s approval are listed in `config/processors.yaml`.', '');
  }
  for (const p of registry.processors) {
    const hosts = Object.entries(policy.cells).flatMap(([cell, c]) => c.hosts.filter((h) => h.processor === p.id).map((h) => `${cell}: ${h.host}:${h.port}`));
    lines.push(
      `## ${p.name} (\`${p.id}\`)`, '',
      `| Field | Value |`, `|---|---|`,
      `| Status | ${p.review.status}${p.approval ? ` (approved by ${p.approval.approved_by} on ${p.approval.approved_on})` : ''} |`,
      `| Role | ${p.role} |`, `| Purpose | ${p.purpose} |`,
      `| Data categories | ${p.data_categories.join(', ')} |`,
      `| Data locations | ${p.data_locations.map((d) => `${d.data}: ${d.location}`).join('; ')} |`,
      `| Sub-processors | ${p.sub_processors.list_url ?? 'unknown'}${p.sub_processors.notice_days !== null ? ` (notice: ${p.sub_processors.notice_days} days)` : ''} |`,
      `| DPA | ${p.terms.dpa} |`, `| Retention | ${p.retention} |`, `| Transfer mechanism | ${p.transfer_mechanism} |`,
      `| Egress hosts | ${hosts.join(', ') || 'none'} |`, `| ADR | ${p.adr} |`,
      `| Destination tested | ${p.destination_test ?? 'not yet'} |`,
      `| Next review | ${p.review.next_review ?? 'n/a'} |`,
      `| Unknowns | ${p.unknowns.join('; ') || 'none'} |`, '',
    );
  }
  return lines.join('\n');
}
